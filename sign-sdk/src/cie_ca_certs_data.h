/**
 * @file cie_ca_certs_data.h
 * @brief Embedded DER encodings of the public Italian CIE certification
 * authority certificates.
 *
 * These are PUBLIC root and intermediate CA certificates issued by the
 * Ministero dell'Interno for the Carta d'Identita Elettronica (CIE) and
 * published in AgID's Trusted List for Italy (TSL-IT), as required by the
 * eIDAS Regulation:
 *
 *   https://eidas.agid.gov.it/TL/TSL-IT.xml
 *
 * They identify certification authorities, not individual cardholders, and
 * are therefore not personal data. They are not present in generic OS/
 * browser trust stores, so a CIE-signed CMS that (per RFC 5280 common
 * practice) omits the issuing chain cannot have its OCSP response or CRL
 * signature verified without them: CCertStore::LoadBuiltInCieCertificates()
 * feeds these into the in-memory certificate store used for that lookup.
 *
 * Regenerate by extracting the relevant <ds:X509Certificate> entries for
 * "Ministero dell'Interno" from the AgID TL above, converting each to DER,
 * e.g.:
 *
 *   openssl x509 -in ca.pem -outform DER -out ca.der
 *
 * and re-verifying the SHA-256 fingerprint recorded above each array
 * against the TL entry before replacing it (see the comment above each
 * array below).
 */

